import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const loaderPath = fileURLToPath(new URL("../native/index.js", import.meta.url));
const typesPath = fileURLToPath(new URL("../native/index.d.ts", import.meta.url));
const prefixPath = fileURLToPath(new URL("./native-loader-prefix.cjs", import.meta.url));
const loader = readFileSync(loaderPath, "utf8");
const prefix = readFileSync(prefixPath, "utf8");
const requireNativeMarker = "function requireNative()";
const markerIndex = loader.indexOf(requireNativeMarker);

if (markerIndex < 0) {
  throw new Error(`could not find ${requireNativeMarker} in ${loaderPath}`);
}

const generatedPrefixStart = loader.indexOf("const { readFileSync } = require('fs')");
const hardenedPrefixStart = loader.indexOf("// This prefix replaces napi-rs's generated libc probe.");
const prefixStart = generatedPrefixStart >= 0 ? generatedPrefixStart : hardenedPrefixStart;
if (prefixStart < 0 || prefixStart >= markerIndex) {
  throw new Error(`could not identify the libc detector in ${loaderPath}`);
}

const header = loader.slice(0, prefixStart).replace(
  "/* auto-generated by NAPI-RS */",
  "/* generated by NAPI-RS; libc detection hardened by scripts/harden-native-loader.mjs */",
);
const hardened = `${header}${prefix}\n${loader.slice(markerIndex)}`;

if (hardened !== loader) {
  writeFileSync(loaderPath, hardened);
  console.log(`hardened ${loaderPath.slice(root.length)}`);
}

const generatedTypes = readFileSync(typesPath, "utf8");
const hardenedTypes = generatedTypes
  .replace(
    /inspectArchiveNative\(([^)]*)\): Promise<unknown>/,
    "inspectArchiveNative($1): Promise<Array<NativeArchiveEntry>>",
  )
  .replace(
    /extractArchiveNative\(([^)]*)\): Promise<unknown>/,
    "extractArchiveNative($1): Promise<void>",
  )
  .replace(
    /readArchiveEntryNative\(([^)]*)\): Promise<unknown>/,
    "readArchiveEntryNative($1): Promise<Buffer>",
  )
  .replace(
    /sha256File\(([^)]*)\): Promise<unknown>/,
    "sha256File($1): Promise<FileHash>",
  )
  .replace(
    /copyFileRangeExclusive\(([^)]*)\): Promise<unknown>/,
    "copyFileRangeExclusive($1): Promise<NativeCopyResult>",
  );
if (hardenedTypes !== generatedTypes) {
  writeFileSync(typesPath, hardenedTypes);
  console.log(`hardened ${typesPath.slice(root.length)}`);
}
